// Regenerates src/lib/legalText.ts from the root POLICY.md and TERMS.md.
// Run: node scripts/gen-legal-text.mjs
// The in-app reader shows plain text, so web-only markup is simplified here:
// front matter and the table of contents are dropped, "> " quote markers removed,
// and [text](url) becomes "text (url)" (or just the url).
import fs from 'node:fs';

const read = (f) => {
  let s = fs.readFileSync(new URL(`../${f}`, import.meta.url), 'utf8').replace(/\r\n/g, '\n');
  s = s.replace(/^---\n[\s\S]*?\n---\n/, '');
  s = s.replace(/^## Contents\n[\s\S]*?(?=^## )/m, '');
  s = s.replace(/^> ?/gm, '');
  s = s.replace(/\[([^\]]+)\]\(([^)]+)\)/g, (_, text, url) => (text === url ? url : `${text} (${url})`));
  return s.replace(/\n{3,}/g, '\n\n').trim();
};

const out = `// GENERATED by scripts/gen-legal-text.mjs from POLICY.md and TERMS.md. Do not edit by hand.
// Shown in-app only when no hosted URL is configured (see src/lib/links.ts).

export const PRIVACY_POLICY_TEXT = ${JSON.stringify(read('POLICY.md'))};

export const TERMS_TEXT = ${JSON.stringify(read('TERMS.md'))};
`;
fs.writeFileSync(new URL('../src/lib/legalText.ts', import.meta.url), out);
console.log('legalText.ts written');
